//! Squashing: replacing a prefix of the history with one baseline migration
//! whose ops create the final state of that prefix.

use std::collections::BTreeMap;
use std::fs;
use std::path::Path;

use anyhow::{Context, Result, bail};

use crate::dhall::{self, label, text_literal};
use crate::executor::{
    creates, key, parse_compression, parse_durability, parse_expiry, parse_segment_size, parse_size,
};
use crate::migrations::{self, BASELINE_SUFFIX, Baseline, Migration, Replaced};
use crate::op::Op;
use crate::rehearsal;

/// Folds a history of ops into the create ops for its final state, in an
/// order that creates parents before children.
pub fn fold<'a>(history: impl IntoIterator<Item = &'a Op>) -> Result<Vec<Op>> {
    let mut state: Vec<Op> = Vec::new();
    for op in history {
        let k = key(op);
        let parent = k.rsplit_once('/').map(|(p, _)| p);
        let existing = state.iter().position(|s| key(s) == k);
        if creates(op) {
            if let Some(p) = parent
                && !state.iter().any(|s| key(s) == p)
            {
                bail!("history creates {k} without creating {p} first");
            }
            match existing {
                Some(i) if conflicts(&state[i], op)? => {
                    bail!("history creates topic {k} twice with different config")
                }
                Some(_) => {}
                None => state.push(op.clone()),
            }
        } else if let Op::UpdateTopic { partitions, message_expiry, max_size, compression, .. } = op {
            let Some(Op::CreateTopic {
                partitions: p,
                message_expiry: e,
                max_size: s,
                compression: c,
                ..
            }) = existing.map(|i| &mut state[i])
            else {
                bail!("history updates topic {k} before creating it");
            };
            if let Some(want) = partitions {
                if want < p {
                    bail!("history reduces topic {k} from {p} to {want} partitions");
                }
                *p = *want;
            }
            if message_expiry.is_some() {
                e.clone_from(message_expiry);
            }
            if max_size.is_some() {
                s.clone_from(max_size);
            }
            if compression.is_some() {
                c.clone_from(compression);
            }
        } else {
            let prefix = format!("{k}/");
            state.retain(|s| {
                let sk = key(s);
                sk != k && !sk.starts_with(&prefix)
            });
        }
    }
    Ok(state)
}

/// Whether re-creating `existing` with `op` fails, mirroring the executor:
/// settings `op` leaves to the server default are not compared.
fn conflicts(existing: &Op, op: &Op) -> Result<bool> {
    let (Op::CreateTopic { partitions: p1, .. }, Op::CreateTopic { partitions: p2, .. }) = (existing, op)
    else {
        return Ok(false);
    };
    if p1 != p2 {
        return Ok(true);
    }
    for ((name, have), (_, want)) in existing.topic_settings().into_iter().zip(op.topic_settings()) {
        if let Some(want) = want
            && !same_setting(name, have, want)?
        {
            return Ok(true);
        }
    }
    Ok(false)
}

/// Compares two values of a topic setting by what they parse to, so `7d`
/// and `7 days` are the same expiry.
fn same_setting(name: &str, have: Option<&String>, want: &str) -> Result<bool> {
    let Some(have) = have else { return Ok(false) };
    Ok(match name {
        "message_expiry" => parse_expiry(have)? == parse_expiry(want)?,
        "max_size" => parse_size(have)? == parse_size(want)?,
        "compression" => parse_compression(have)? == parse_compression(want)?,
        "segment_size" => parse_segment_size(have)? == parse_segment_size(want)?,
        "durability" => parse_durability(have)? == parse_durability(want)?,
        _ => unreachable!("unknown topic setting {name}"),
    })
}

/// Renders a baseline file. `per_env` maps each environment to what the
/// baseline must evaluate to there; values shared by every environment are
/// written once, the rest with `merge … env.kind`.
pub fn render(per_env: &BTreeMap<String, Baseline>) -> String {
    let first = per_env.values().next().expect("at least one environment");
    let mut out = String::from(
        "-- Generated by `iggy-migrate squash`. Servers that applied every migration in\n\
         -- `replaces` mark this baseline applied without running it; new servers run\n\
         -- its ops. Do not edit: checksums of the replaced migrations are recorded here.\n",
    );

    out.push_str("{ replaces =\n");
    for (i, replaced) in first.replaces.iter().enumerate() {
        let checksum = by_env(per_env, |b| text_literal(&b.replaces[i].checksum));
        let parent = match &replaced.parent {
            Some(p) => format!("Some {}", text_literal(p)),
            None => "None Text".into(),
        };
        let sep = if i == 0 { "[" } else { "," };
        out.push_str(&format!(
            "  {sep} {{ id = {}, checksum = {checksum}, parent = {parent} }}\n",
            text_literal(&replaced.id)
        ));
    }
    out.push_str("  ]\n");

    out.push_str(&format!(", ops =\n    {}\n}}\n", render_ops(per_env)));
    out
}

fn by_env(per_env: &BTreeMap<String, Baseline>, f: impl Fn(&Baseline) -> String) -> String {
    merge_values(per_env.iter().map(|(env, b)| (env.as_str(), f(b))).collect())
}

/// One value if every environment agrees, else `merge { … } env.kind`.
fn merge_values(values: Vec<(&str, String)>) -> String {
    if values.iter().all(|(_, v)| *v == values[0].1) {
        return values[0].1.clone();
    }
    let arms: Vec<String> = values.iter().map(|(env, v)| format!("{} = {v}", label(env))).collect();
    format!("merge {{ {} }} env.kind", arms.join(", "))
}

/// Renders the ops list. When every environment creates the same resources
/// in the same order, differences are rendered per op or per field, so the
/// shared structure is written once.
fn render_ops(per_env: &BTreeMap<String, Baseline>) -> String {
    let lists: Vec<(&str, &Vec<Op>)> = per_env.iter().map(|(e, b)| (e.as_str(), &b.ops)).collect();
    let keys = |ops: &Vec<Op>| ops.iter().map(key).collect::<Vec<_>>();
    if !lists.iter().all(|(_, ops)| keys(ops) == keys(lists[0].1)) {
        return by_env(per_env, |b| list(b.ops.iter().map(render_op).collect()));
    }
    let items = (0..lists[0].1.len())
        .map(|i| {
            let ops: Vec<(&str, &Op)> = lists.iter().map(|(e, ops)| (*e, &ops[i])).collect();
            render_op_by_env(&ops)
        })
        .collect();
    list(items)
}

fn list(items: Vec<String>) -> String {
    if items.is_empty() {
        return "[] : List Op".into();
    }
    let lines: Vec<String> = items
        .iter()
        .enumerate()
        .map(|(i, item)| format!("{} {item}", if i == 0 { "[" } else { "," }))
        .collect();
    format!("{}\n    ]", lines.join("\n    "))
}

fn render_op_by_env(ops: &[(&str, &Op)]) -> String {
    let values = |f: &dyn Fn(&Op) -> Option<String>| -> Option<String> {
        let vs: Vec<(&str, Option<String>)> = ops.iter().map(|(e, op)| (*e, f(op))).collect();
        if vs.iter().all(|(_, v)| v.is_none()) {
            return None;
        }
        let rendered = vs
            .into_iter()
            .map(|(e, v)| (e, v.unwrap_or_else(|| "None Text".into())))
            .collect();
        Some(merge_values(rendered))
    };
    let Op::CreateTopic { stream, name, .. } = ops[0].1 else {
        return merge_values(ops.iter().map(|(e, op)| (*e, render_op(op))).collect());
    };
    let partitions = values(&|op| match op {
        Op::CreateTopic { partitions, .. } => Some(partitions.to_string()),
        _ => None,
    })
    .filter(|p| p != "1");
    let mut fields = vec![format!("stream = {}", text_literal(stream)), format!("name = {}", text_literal(name))];
    if let Some(p) = partitions {
        fields.push(format!("partitions = {p}"));
    }
    for (i, (setting, _)) in ops[0].1.topic_settings().into_iter().enumerate() {
        let value = values(&|op| {
            Some(op.topic_settings()[i].1.map_or("None Text".into(), |v| format!("Some {}", text_literal(v))))
        })
        .filter(|v| v != "None Text");
        if let Some(v) = value {
            fields.push(format!("{setting} = {v}"));
        }
    }
    format!("Op.CreateTopic Topic::{{ {} }}", fields.join(", "))
}

fn render_op(op: &Op) -> String {
    let t = |s: &str| text_literal(s);
    match op {
        Op::CreateStream { name } => format!("Op.CreateStream {{ name = {} }}", t(name)),
        Op::CreateTopic { .. } => render_op_by_env(&[("", op)]),
        Op::CreateConsumerGroup { stream, topic, name } => format!(
            "Op.CreateConsumerGroup {{ stream = {}, topic = {}, name = {} }}",
            t(stream),
            t(topic),
            t(name)
        ),
        Op::UpdateTopic { .. }
        | Op::DeleteStream { .. }
        | Op::DeleteTopic { .. }
        | Op::DeleteConsumerGroup { .. } => {
            unreachable!("a folded state contains only creates")
        }
    }
}

/// Checks that `source` evaluates back to exactly `per_env` in every
/// environment.
pub fn check_round_trip(source: &str, per_env: &BTreeMap<String, Baseline>) -> Result<()> {
    let all: Vec<String> = per_env.keys().cloned().collect();
    for (env, want) in per_env {
        let got: Baseline =
            dhall::eval_as(source, &dhall::Env { name: env.clone(), all: all.clone() })?;
        if got.replaces != want.replaces || got.ops != want.ops {
            bail!("generated baseline does not evaluate to the squashed state in env {env}");
        }
    }
    Ok(())
}

pub fn replaced(id: &str, checksum: &str) -> Replaced {
    Replaced { id: id.into(), checksum: checksum.into(), parent: None }
}

/// The `replaces` list for squashing `prefix`: each migration, plus whatever
/// any baseline among them replaced, linked to that baseline.
fn replaces_for(prefix: &[Migration]) -> Vec<Replaced> {
    let mut out = Vec::new();
    for m in prefix {
        out.push(replaced(&m.id, &m.checksum));
        for r in &m.replaces {
            out.push(Replaced { parent: Some(r.parent.clone().unwrap_or_else(|| m.id.clone())), ..r.clone() });
        }
    }
    out
}

/// Squashes every migration up to and including `through` (all of them by
/// default) into one baseline, after proving in Docker that the baseline
/// produces the same state as the history in every environment.
pub async fn run(dir: &Path, environments: &[String], through: Option<&str>, image: &str) -> Result<()> {
    let mut loaded = BTreeMap::new();
    for env in environments {
        let e = dhall::Env { name: env.clone(), all: environments.to_vec() };
        loaded.insert(env.clone(), migrations::load_dir(dir, &e)?);
    }
    let ids: Vec<String> = loaded.values().next().into_iter().flatten().map(|m| m.id.clone()).collect();
    let end = match through {
        Some(t) => ids.iter().position(|id| id == t).with_context(|| format!("no migration {t}"))? + 1,
        None => ids.len(),
    };
    if end < 2 {
        bail!("need at least two migrations to squash");
    }
    let (squashed, rest) = ids.split_at(end);
    let last_ts = squashed[end - 1].split_once('_').map_or("", |(ts, _)| ts);
    let id = format!("{last_ts}{BASELINE_SUFFIX}");
    if squashed.contains(&id) || rest.iter().any(|r| *r <= id) {
        bail!("cannot name the baseline {id}: it must sort after every migration it replaces and before the rest");
    }

    let mut per_env = BTreeMap::new();
    for (env, migrations) in &loaded {
        let prefix = &migrations[..end];
        let replaces = replaces_for(prefix);
        let ops = fold(prefix.iter().flat_map(|m| &m.ops))
            .with_context(|| format!("env {env}: cannot fold history"))?;
        per_env.insert(env.clone(), Baseline { replaces, ops });
    }
    let source = render(&per_env);
    check_round_trip(&source, &per_env)?;

    let server = rehearsal::Server::start(image).await?;
    for (env, migrations) in &loaded {
        let baseline = &per_env[env];
        server.reset().await?;
        let history: Vec<&Migration> = migrations[..end].iter().collect();
        rehearsal::apply(&server.client, &history)
            .await
            .with_context(|| format!("env {env}: history does not apply from scratch, so it cannot be squashed"))?;
        let want = rehearsal::snapshot(&server.client).await?;
        server.reset().await?;
        let migration = Migration {
            id: id.clone(),
            ops: baseline.ops.clone(),
            checksum: String::new(),
            replaces: baseline.replaces.clone(),
        };
        rehearsal::apply(&server.client, &[&migration]).await.with_context(|| format!("env {env}: baseline does not apply"))?;
        let got = rehearsal::snapshot(&server.client).await?;
        if got != want {
            bail!(
                "env {env}: baseline does not reproduce the history's state\n  history:  {want:?}\n  baseline: {got:?}"
            );
        }
        crate::out!("env {env}: baseline reproduces {} resource(s)", want.len());
    }
    drop(server);

    let path = dir.join(format!("{id}.dhall"));
    fs::write(&path, &source)?;
    for old in squashed {
        fs::remove_file(dir.join(format!("{old}.dhall")))?;
    }
    crate::out!("squashed {} migration(s) into {}", squashed.len(), path.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn stream(name: &str) -> Op {
        Op::CreateStream { name: name.into() }
    }

    fn topic(stream: &str, name: &str, partitions: u64) -> Op {
        Op::CreateTopic {
            stream: stream.into(),
            name: name.into(),
            partitions,
            message_expiry: None,
            max_size: None,
            compression: None,
            segment_size: None,
            durability: None,
        }
    }

    fn group(stream: &str, topic: &str, name: &str) -> Op {
        Op::CreateConsumerGroup { stream: stream.into(), topic: topic.into(), name: name.into() }
    }

    #[test]
    fn deletes_remove_descendants_and_recreates_move_to_the_end() {
        let history = vec![
            stream("a"),
            topic("a", "t", 1),
            group("a", "t", "g"),
            stream("b"),
            Op::DeleteTopic { stream: "a".into(), name: "t".into() },
            topic("a", "t", 4),
            Op::DeleteStream { name: "b".into() },
            stream("a"),
        ];
        assert_eq!(fold(&history).unwrap(), vec![stream("a"), topic("a", "t", 4)]);
    }

    fn update(partitions: Option<u64>, expiry: Option<&str>) -> Op {
        Op::UpdateTopic {
            stream: "a".into(),
            name: "t".into(),
            partitions,
            message_expiry: expiry.map(Into::into),
            max_size: None,
            compression: None,
        }
    }

    #[test]
    fn updates_are_folded_into_the_create() {
        let history =
            vec![stream("a"), topic("a", "t", 1), update(Some(4), None), update(None, Some("7d"))];
        let Op::CreateTopic { partitions, message_expiry, .. } = &fold(&history).unwrap()[1] else {
            panic!("expected a topic");
        };
        assert_eq!((*partitions, message_expiry.as_deref()), (4, Some("7d")));
    }

    #[test]
    fn invalid_updates_in_history_are_errors() {
        assert!(fold(&[stream("a"), update(Some(4), None)]).is_err());
        assert!(fold(&[stream("a"), topic("a", "t", 4), update(Some(2), None)]).is_err());
    }

    #[test]
    fn conflicting_topic_config_is_an_error() {
        let history = vec![stream("a"), topic("a", "t", 1), topic("a", "t", 2)];
        assert!(fold(&history).is_err());
    }

    #[test]
    fn recreating_a_topic_compares_like_the_executor() {
        let with_expiry = |e: Option<&str>| Op::CreateTopic {
            stream: "a".into(),
            name: "t".into(),
            partitions: 1,
            message_expiry: e.map(Into::into),
            max_size: None,
            compression: None,
            segment_size: None,
            durability: None,
        };
        let state = fold(&[stream("a"), with_expiry(Some("7d")), with_expiry(None)]).unwrap();
        assert_eq!(state, vec![stream("a"), with_expiry(Some("7d"))]);
        assert!(fold(&[stream("a"), with_expiry(Some("7d")), with_expiry(Some("7days"))]).is_ok());
        assert!(fold(&[stream("a"), with_expiry(Some("7d")), with_expiry(Some("1d"))]).is_err());
    }

    #[test]
    fn missing_parent_is_an_error() {
        assert!(fold(&[topic("a", "t", 1)]).is_err());
    }

    fn baseline(checksum: &str, ops: Vec<Op>) -> Baseline {
        Baseline { replaces: vec![replaced("20260101000000_x", checksum)], ops }
    }

    #[test]
    fn render_round_trips_shared_and_per_env_values() {
        let shared = vec![stream("a"), topic("a", "t", 3)];
        let mut per_env = BTreeMap::new();
        per_env.insert("dev".to_string(), baseline("sha256:1", shared.clone()));
        per_env.insert("prod".to_string(), baseline("sha256:1", shared.clone()));
        let source = render(&per_env);
        assert!(!source.contains("merge"), "{source}");
        check_round_trip(&source, &per_env).unwrap();

        per_env.insert(
            "prod".to_string(),
            baseline("sha256:2", vec![stream("a"), topic("a", "t", 12), group("a", "t", "g")]),
        );
        let source = render(&per_env);
        assert!(source.contains("merge"), "{source}");
        check_round_trip(&source, &per_env).unwrap();
    }

    #[test]
    fn render_merges_individual_fields() {
        let topic_with = |partitions, expiry: Option<&str>| Op::CreateTopic {
            stream: "a".into(),
            name: "t".into(),
            partitions,
            message_expiry: expiry.map(Into::into),
            max_size: None,
            compression: None,
            segment_size: None,
            durability: None,
        };
        let mut per_env = BTreeMap::new();
        per_env.insert("dev".to_string(), baseline("sha256:1", vec![stream("a"), topic_with(1, None)]));
        per_env.insert("prod".to_string(), baseline("sha256:1", vec![stream("a"), topic_with(12, Some("7d"))]));
        let source = render(&per_env);
        assert!(source.contains("partitions = merge { dev = 1, prod = 12 } env.kind"), "{source}");
        assert!(source.contains(r#"message_expiry = merge { dev = None Text, prod = Some "7d" } env.kind"#), "{source}");
        assert_eq!(source.matches("Op.CreateStream").count(), 1, "{source}");
        check_round_trip(&source, &per_env).unwrap();
    }

    #[test]
    fn squashing_a_baseline_carries_its_replaces_along() {
        let m = |id: &str, replaces: Vec<Replaced>| Migration {
            id: id.into(),
            ops: vec![],
            checksum: format!("c-{id}"),
            replaces,
        };
        let b1 = m("3_baseline", vec![replaced("1_a", "c-1_a"), replaced("2_b", "c-2_b")]);
        let r = replaces_for(&[b1, m("4_c", vec![])]);
        let summary: Vec<(&str, Option<&str>)> =
            r.iter().map(|r| (r.id.as_str(), r.parent.as_deref())).collect();
        assert_eq!(
            summary,
            vec![("3_baseline", None), ("1_a", Some("3_baseline")), ("2_b", Some("3_baseline")), ("4_c", None)]
        );
    }

    #[test]
    fn render_handles_empty_state() {
        let mut per_env = BTreeMap::new();
        per_env.insert("dev".to_string(), baseline("sha256:1", vec![]));
        check_round_trip(&render(&per_env), &per_env).unwrap();
    }
}
